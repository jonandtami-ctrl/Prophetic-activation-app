function resolveActivations(): Activation[] {
  const bySlug = new Map(seeds.map((s) => [s.slug, s]));
  return seeds.map((s) => {
    const { relatedSlugs, ...rest } = s;
    return {
      ...rest,
      completionStatus: 'not-started',
      favourite: false,
      relatedActivationIds: relatedSlugs.map((slug) => bySlug.get(slug)?.id).filter((id): id is string => Boolean(id)),
    };
  });
}

export const ACTIVATIONS: Activation[] = resolveActivations();

export function getActivationById(id: string): Activation | undefined {
  return ACTIVATIONS.find((a) => a.id === id);
}

export function activationsByCategory(category: ActivationCategory): Activation[] {
  return ACTIVATIONS.filter((a) => a.category === category);
}

export function activationsByLevel(level: ActivationLevel): Activation[] {
  return ACTIVATIONS.filter((a) => a.level === level);
}
